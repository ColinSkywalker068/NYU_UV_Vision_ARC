#!/usr/bin/env python3
"""Snapshot the actual Type C sentry vision filter/slew functions for offline tests.

Does not build, flash or access a robot. --check rejects firmware/reference drift.
Joint-window clamping, RC acceptance and physical PID dynamics are outside this fixture.
"""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess


def function(source, name):
    match = re.search(r"^static (?:inline )?(?:float|void) " + name + r"\([^;{}]*\)\s*\{", source, re.M)
    if not match:
        raise ValueError(f"Missing production function {name}")
    start = source.index("{", match.start())
    depth = 1
    end = start + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[match.start():end]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--typec-repo", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = (args.typec_repo / "application/cmd/robot_cmd.c").read_text()
    config = (args.typec_repo / "application/robot_configs/robot_sentry.h").read_text()
    revision = subprocess.check_output(["git", "-C", str(args.typec_repo), "rev-parse", "HEAD"], text=True).strip()
    names = ["VISION_ACCEL_LIMITED_SLEW_ENABLE", "VISION_SLEW_ERROR_GAIN_S",
             "VISION_YAW_MAX_SLEW_DEG_S", "VISION_PITCH_MAX_SLEW_DEG_S",
             "VISION_YAW_MAX_ACCEL_DEG_S2", "VISION_PITCH_MAX_ACCEL_DEG_S2",
             "VISION_TARGET_FILTER_ALPHA", "VISION_TARGET_VEL_FILTER_ALPHA", "VISION_TARGET_ACC_FILTER_ALPHA"]
    definitions = []
    for name in names:
        match = re.search(r"^#define " + name + r"\s+([^\s/]+)", config, re.M)
        if not match:
            match = re.search(r"^#ifndef " + name + r"\s*\n#define " + name + r"\s+([^\s/]+)", source, re.M)
        if not match:
            raise ValueError(f"Missing sentry definition {name}")
        definitions.append(f"#define {name} {match[1]}")
    extracted = "\n\n".join(function(source, name) for name in ["LimitDelta", "FiniteOrZero", "ResetVisionCmdFilter",
                                                                          "UpdateVisionTargetFilter", "ApplyVisionAxisSlew"])
    identity = hashlib.sha256(("\n".join(definitions) + extracted).encode()).hexdigest()
    preamble = f"""// Generated by tools/snapshot-typec-vision.py; do not edit by hand.
// Type C revision: {revision}
// Extracted function/config SHA256: {identity}
// Reference generation only: no firmware, motor, RC or firing access.
#pragma once
#include <cmath>
#include <cstdint>
namespace sentry_reference {{
using std::isfinite;
"""
    shim = """
// Fixture shims. All test angles remain away from physical joint stops; encoder
// clamping and motor PID behavior are not validated by this reference test.
static struct {float yaw_actual_angle; float pitch_actual_angle;} gimbal_fetch_data{};
static uint8_t vision_cmd_filter_inited = 0;
static float vision_yaw_cmd_filtered, vision_pitch_cmd_filtered;
static float vision_yaw_target_filtered, vision_pitch_target_filtered;
static float vision_yaw_vel_filtered_deg_s, vision_pitch_vel_filtered_deg_s;
static float vision_yaw_acc_filtered_deg_s2, vision_pitch_acc_filtered_deg_s2;
static float vision_yaw_slew_rate_deg_s, vision_pitch_slew_rate_deg_s;
static float vision_target_filter_alpha_runtime = VISION_TARGET_FILTER_ALPHA;
static float vision_target_vel_filter_alpha_runtime = VISION_TARGET_VEL_FILTER_ALPHA;
static inline float ClampYawCmdToEncoderWindow(float target, float) {return target;}
"""
    result = preamble + "\n".join(definitions) + "\n" + shim + extracted + "\n} // namespace sentry_reference\n"
    path = Path(__file__).resolve().parents[1] / "yolo_cpp/test/fixtures/typec_vision_reference.hpp"
    if args.check:
        if not path.exists() or path.read_text() != result:
            raise SystemExit("Type C reference differs: review and regenerate before interpreting tests")
        print(f"Verified Type C {revision} reference {identity}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(result)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
